async function main() {
  console.log('DataScout — Cassette Regeneration Script');
  console.log('=========================================');
  if (DRY_RUN) console.log('DRY RUN – no files will be written or deleted.\n');

  const [promptText, corpusText, jsonSchema] = await Promise.all([
    readFile(PROMPT_PATH, 'utf8'),
    readFile(CORPUS_PATH, 'utf8'),
    getActualSchema(),
  ]);

  console.log(`Prompt file : ${PROMPT_PATH}`);
  console.log(`Corpus file : ${CORPUS_PATH}`);
  console.log(`Cassette dir: ${CASSETTE_DIR}\n`);

  // Parse development cases only
  const lines = corpusText
    .split(/\r?\n/)
    .filter((l) => l.trim() !== '')
    .map((l) => JSON.parse(l));

  const devCases = lines.filter((c) => c.split === 'development');
  console.log(
    `Found ${lines.length} total corpus cases, ${devCases.length} development cases.\n`,
  );

  // Compute expected cassette keys for each dev case
  const cassetteEntries = await Promise.all(
    devCases.map(async (c) => {
      const req = {
        task: 'extract',
        promptVersion: EXTRACTION_PROMPT_VERSION,
        system: promptText,
        user: c.input,
        jsonSchema,
        maxOutputTokens: EXTRACTION_MAX_OUTPUT_TOKENS,
        timeoutMs: EXTRACTION_TIMEOUT_MS,
      };
      const key = stableRequestKey(req);
      const filename = `${key}.json`;
      // Always store the full expected object as the cassette output.
      // When topic === null, the extraction code parses the schema-valid object
      // (which has topic: null) and then triggers the clarification path.
      const output = c.expected;
      return { case_id: c.case_id, key, filename, output };
    }),
  );

  const newKeys = new Set(cassetteEntries.map((e) => e.filename));

  // List existing cassettes
  let existingFiles = [];
  try {
    existingFiles = await readdir(CASSETTE_DIR);
  } catch {
    console.log(`Creating cassette directory: ${CASSETTE_DIR}`);
    if (!DRY_RUN) await mkdir(CASSETTE_DIR, { recursive: true });
  }

  const toDelete = existingFiles.filter(
    (f) => f.endsWith('.json') && !newKeys.has(f),
  );
  const toWrite = cassetteEntries.filter(
    (e) => !existingFiles.includes(e.filename),
  );
  const unchanged = cassetteEntries.filter((e) =>
    existingFiles.includes(e.filename),
  );

  console.log(`Cassettes to write  : ${toWrite.length}`);
  console.log(`Cassettes unchanged : ${unchanged.length}`);
  console.log(`Cassettes to delete : ${toDelete.length}\n`);

  // Write new cassettes
  for (const entry of toWrite) {
    const cassette = {
      output: entry.output,
      modelId: 'development-gold-fixture-v0.1',
      usage: { inputTokens: 0, outputTokens: 0 },
    };
    const dest = join(CASSETTE_DIR, entry.filename);
    console.log(`  WRITE  ${entry.filename}  (${entry.case_id})`);
    if (!DRY_RUN) {
      await writeFile(dest, JSON.stringify(cassette, null, 2) + '\n', 'utf8');
    }
  }

  // Delete stale cassettes
  for (const filename of toDelete) {
    console.log(`  DELETE ${filename}`);
    if (!DRY_RUN) {
      await unlink(join(CASSETTE_DIR, filename));
    }
  }

  if (unchanged.length > 0 && toWrite.length === 0 && toDelete.length === 0) {
    console.log('\n✅ All cassettes are already up to date.');
  } else if (!DRY_RUN) {
    console.log(
      `\n✅ Done. Wrote ${toWrite.length} new cassettes, deleted ${toDelete.length} stale cassettes.`,
    );
  } else {
    console.log(
      `\n(dry-run) Would write ${toWrite.length}, delete ${toDelete.length}.`,
    );
  }
}

main().catch((err) => {
  console.error('Error:', err instanceof Error ? err.message : err);
  process.exit(1);
});
