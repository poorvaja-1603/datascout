/**
 * regenerate-cassettes.mjs
 *
 * Regenerates the corpus-cassettes directory so that cassette filenames
 * match the current SHA-256 key derived from:
 *   { task, promptVersion, system (prompt file), user (corpus input), jsonSchema }
 *
 * The cassette OUTPUT is always the gold-annotation from the corpus expected field.
 * This means no model inference is required.
 *
 * Run with: node evals/scripts/regenerate-cassettes.mjs [--dry-run]
 * Or:        npx tsx evals/scripts/regenerate-cassettes.mjs [--dry-run]
 */

import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile, unlink, mkdir } from 'node:fs/promises';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '../..');

const PROMPT_PATH = join(repoRoot, 'packages/ai/prompts/extract.v1.md');
const CORPUS_PATH = join(repoRoot, 'evals/requirements-v0.1.jsonl');
const CASSETTE_DIR = join(
  repoRoot,
  'packages/ai/test/fixtures/corpus-cassettes',
);

const EXTRACTION_PROMPT_VERSION = 'extract-v1';
const EXTRACTION_MAX_OUTPUT_TOKENS = 512;
const EXTRACTION_TIMEOUT_MS = 15_000;

const DRY_RUN = process.argv.includes('--dry-run');

// ── Canonical JSON (must exactly match client.ts canonicalJson) ──────────────
function canonicalJson(value) {
  if (Array.isArray(value)) {
    return `[${value.map(canonicalJson).join(',')}]`;
  }
  if (typeof value === 'object' && value !== null) {
    const fields = Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`);
    return `{${fields.join(',')}}`;
  }
  return JSON.stringify(value);
}

function stableRequestKey(req) {
  const identity = canonicalJson({
    task: req.task,
    promptVersion: req.promptVersion,
    system: req.system,
    user: req.user,
    jsonSchema: req.jsonSchema,
  });
  return createHash('sha256').update(identity).digest('hex');
}

// ── Load the real schema from contracts (works with tsx; falls back to dist) ─
